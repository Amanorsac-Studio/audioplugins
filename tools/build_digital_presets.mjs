// --- validate every id against the contract before writing ---------------
const expand = (id, base) => {
  const slots = { D01: { band: 24, xover: 0 }, D02: { band: 12 }, D03: { band: 6, xover: 5 },
                  D07: { zone: 6, xover: 5 }, D08: { tap: 8 }, D10: { band: 5, xover: 4 } }[id] || {};
  const family = base.includes(".") ? base.split(".")[0] : "";
  return slots[family] ? slots[family] : 0;
};

let problems = 0;
for (const [id, data] of Object.entries(banks)) {
  const spec = JSON.parse(readFileSync(`specs/plugins/${id}.json`, "utf8"));
  const contract = new Set(spec.parameters.map((x) => x.id.split("\n")[0].trim()));
  for (const preset of data.presets)
    for (const key of Object.keys(preset.values)) {
      const base = key.replace(/\.(\d{2})\./, ".");
      const index = key.match(/\.(\d{2})\./);
      if (!contract.has(base)) { console.error(`${id} "${preset.name}": no such control ${key}`); ++problems; continue; }
      if (index && Number(index[1]) > expand(id, base)) { console.error(`${id} "${preset.name}": slot out of range ${key}`); ++problems; }
    }
  writeFileSync(`presets/factory/${id}_factory.json`, JSON.stringify(data, null, 2) + "\n");
  console.log(`${id}  ${data.presets.length} presets  ${data.categories.join(", ")}`);
}
console.log(problems === 0 ? "all ids check out against the contracts" : `${problems} problem(s)`);
process.exit(problems === 0 ? 0 : 1);
