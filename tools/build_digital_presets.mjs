const bank = (id, presets) => ({
  plugin_id: id,
  bank: "Amanorsac Digital",
  author: "Amanorsac Studio",
  note: "Factory bank. Starting points, not destinations.",
  categories: [...new Set(presets.map((p) => p.category))],
  presets,
});

const p = (name, category, tags, values) => ({ name, category, tags, values });

// --- helpers for the indexed families -------------------------------------
const pad = (n) => String(n).padStart(2, "0");
/** eq(1, {frequency: 80, gain: -2, q: 0.9, type: "bell"}) -> band.01.* */
const slot = (family, index, fields) =>
  Object.fromEntries(Object.entries(fields).map(([k, v]) => [`${family}.${pad(index)}.${k}`, v]));
const bands = (list) => Object.assign({}, ...list.map((f, i) => slot("band", i + 1, f)));
const zones = (list) => Object.assign({}, ...list.map((f, i) => slot("zone", i + 1, f)));
const taps = (list) => Object.assign({}, ...list.map((f, i) => slot("tap", i + 1, f)));
const xovers = (list) => Object.assign({}, ...list.map((f, i) => slot("xover", i + 1, { frequency: f })));
/** Bands past the ones a preset uses are switched out so they cannot colour it. */
const onlyBands = (count, total, key = "enabled") => {
  const out = {};
  for (let i = count + 1; i <= total; ++i) out[`band.${pad(i)}.${key}`] = false;
  return out;
};

